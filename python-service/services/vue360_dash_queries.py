CREDITS_DASH_LIST = """
SELECT
    p.ACCOUNT_NUMBER AS LOAN_NUMBER,
    NVL(f.CUSTOMER_NO, p.CR_PROD_AC) AS CLIENT_ID,
    p.CHARGE_AFFAIRE AS CLIENT_NAME,
    0 AS FINANCED_AMOUNT,
    0 AS OUTSTANDING,
    'active' AS STATUS,
    0 AS PAR_DAYS,
    p.CR_PROD_AC AS PRODUCT_TYPE,
    p.BRANCH_CODE,
    p.CHARGE_AFFAIRE AS MANAGER,
    TO_CHAR(p.DATE_MISE_EN_PLACE, 'YYYY-MM-DD') AS DISBURSEMENT_DATE,
    NULL AS MATURITY_DATE,
    NULL AS NEXT_DUE_DATE,
    0 AS CAPITAL_DUE,
    0 AS ACCRUED_INTEREST,
    0 AS PENALTIES,
    0 AS TOTAL_REPAID
FROM DASH_PRET p
LEFT JOIN TMP_CLIENTS_FLEX f ON f.EXT_REF_NO = p.CR_PROD_AC
WHERE p.MIGRATION_DATETIME = (
    SELECT MAX(MIGRATION_DATETIME) FROM DASH_PRET
)
  {client_filter}
  {branch_filter}
ORDER BY p.DATE_MISE_EN_PLACE DESC
FETCH FIRST :limit ROWS ONLY
"""
