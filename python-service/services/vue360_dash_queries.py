CUSTOMERS_LIST_DASH = f"""
SELECT
    NVL(f.CUSTOMER_NO, c.CUST_AC_NO) AS CUSTOMER_NO,
    NVL(f.CUSTOMER_NO, c.CUST_AC_NO) AS SC_CUSTOMER_NO,
    c.CUSTOMER_NAME1 AS FULL_NAME,
    c.CUSTOMER_NAME1 AS FIRST_NAME,
    '' AS LAST_NAME,
    NVL(f.EXT_REF_NO, c.CUST_AC_NO) AS MATRICULE,
    c.CUST_AC_NO AS ACCOUNT_NUMBER,
    c.CONTACT_NUMBER AS PHONE,
    NVL(c.LIB_SSECT, c.TYPE_COMPTE) AS SEGMENT,
    'active' AS STATUS,
    c.LOCAL_BRANCH AS BRANCH_CODE,
    0 AS TOTAL_OUTSTANDING,
    0 AS SAVINGS_BALANCE,
    0 AS ACTIVE_CREDITS_COUNT,
    0 AS PAR_DAYS
FROM CUSTOMERS c
LEFT JOIN TMP_CLIENTS_FLEX f
    ON UPPER(TRIM(f.CUSTOMER_NAME1)) = UPPER(TRIM(c.CUSTOMER_NAME1))
WHERE {_LATEST_CUSTOMERS}
  AND c.LOCAL_BRANCH IN ({{branch_placeholders}})
ORDER BY c.CUSTOMER_NAME1
FETCH FIRST :limit ROWS ONLY
"""

